<?php

declare(strict_types=1);

namespace JotLibrary;

use WP_Query;
use WP_Term;

final class Library_Block {
	/** Upper bound on entries rendered by repeated "Load more" requests. */
	private const MAX_LOADED = 240;

	public static function register(): void {
		register_block_type(JOT_LIBRARY_DIR . 'blocks/library');
	}

	/** @param array<string,mixed> $attributes */
	public static function render(array $attributes): string {
		$defaults = Settings::get();
		$page_size = min(48, max(1, absint($attributes['postsPerPage'] ?? $defaults['entries_per_page'])));
		$show_search = ! isset($attributes['showSearch']) || (bool) $attributes['showSearch'];
		$search = isset($_GET['jot_search']) ? sanitize_text_field(wp_unslash((string) $_GET['jot_search'])) : '';
		$topic = isset($_GET['jot_topic']) ? sanitize_title(wp_unslash((string) $_GET['jot_topic'])) : '';
		// "Load more" is cumulative: page N shows every entry up to N, so the URL can be
		// reloaded or shared and still lands on the same place without JavaScript.
		$page = isset($_GET['jot_page']) ? max(1, absint($_GET['jot_page'])) : 1;
		$page = min($page, max(1, intdiv(self::MAX_LOADED, $page_size)));
		$args = array(
			'post_type' => Post_Type::TYPE,
			'post_status' => 'publish',
			'posts_per_page' => $page_size * $page,
			'paged' => 1,
			's' => $search,
			'ignore_sticky_posts' => true,
		);
		if ('' !== $topic) {
			$args['tax_query'] = array(array('taxonomy' => Post_Type::TAXONOMY, 'field' => 'slug', 'terms' => $topic));
		}

		$query = new WP_Query($args);
		$wrapper = get_block_wrapper_attributes(array('class' => 'jot-library'));
		$action_url = get_permalink();
		if (! is_string($action_url) || '' === $action_url) {
			$action_url = home_url('/');
		}
		$search_id = wp_unique_id('jot-library-search-');
		$topics = get_terms(array('taxonomy' => Post_Type::TAXONOMY, 'hide_empty' => true));
		if (is_wp_error($topics)) {
			$topics = array();
		}
		$count = esc_html(sprintf(_n('%s entry', '%s entries', $query->found_posts, 'jot-library'), number_format_i18n($query->found_posts)));
		$context = array('action_url' => $action_url, 'search' => $search, 'topic' => $topic);
		ob_start();
		?>
		<section <?php echo $wrapper; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by Core. ?>>
			<?php if ($show_search) : ?>
				<div class="jot-library__toolbar">
					<form class="jot-library__search" method="get" action="<?php echo esc_url($action_url); ?>" role="search">
						<label class="screen-reader-text" for="<?php echo esc_attr($search_id); ?>"><?php esc_html_e('Search bookmarks', 'jot-library'); ?></label>
						<input id="<?php echo esc_attr($search_id); ?>" name="jot_search" type="search" value="<?php echo esc_attr($search); ?>" placeholder="<?php echo esc_attr__('Search the library', 'jot-library'); ?>">
						<?php if ('' !== $topic) : ?>
							<input type="hidden" name="jot_topic" value="<?php echo esc_attr($topic); ?>">
						<?php endif; ?>
						<button type="submit"><?php esc_html_e('Search', 'jot-library'); ?></button>
					</form>
					<p class="jot-library__count" role="status"><?php echo $count; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Escaped above. ?></p>
					<?php if (array() !== $topics) : ?>
						<nav class="jot-library__topic-nav" aria-label="<?php esc_attr_e('Topics', 'jot-library'); ?>">
							<ul>
								<li><a href="<?php echo esc_url(self::filter_url($context, '')); ?>"<?php echo '' === $topic ? ' aria-current="page"' : ''; ?>><?php esc_html_e('All', 'jot-library'); ?></a></li>
								<?php foreach ($topics as $term) : ?>
									<li><a href="<?php echo esc_url(self::filter_url($context, $term->slug)); ?>"<?php echo $topic === $term->slug ? ' aria-current="page"' : ''; ?>><?php echo esc_html($term->name); ?></a></li>
								<?php endforeach; ?>
							</ul>
						</nav>
					<?php endif; ?>
				</div>
			<?php else : ?>
				<p class="jot-library__count" role="status"><?php echo $count; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Escaped above. ?></p>
			<?php endif; ?>

			<?php if ($query->have_posts()) : ?>
				<ol class="jot-library__entries">
					<?php $position = 0; ?>
					<?php while ($query->have_posts()) : $query->the_post(); ?>
						<?php echo self::entry(get_the_ID(), $context, ++$position); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Method escapes dynamic values. ?>
					<?php endwhile; ?>
				</ol>
				<?php echo self::load_more($query, $context, $page, $page_size); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Method escapes dynamic values. ?>
			<?php elseif ('' !== $search || '' !== $topic) : ?>
				<div class="jot-library__empty"><h3><?php esc_html_e('No matching entries', 'jot-library'); ?></h3><p><?php esc_html_e('Try another search or clear the filters.', 'jot-library'); ?></p><a href="<?php echo esc_url($action_url); ?>"><?php esc_html_e('Clear filters', 'jot-library'); ?></a></div>
			<?php else : ?>
				<div class="jot-library__empty"><h3><?php esc_html_e('The library is ready for its first entry', 'jot-library'); ?></h3><p><?php esc_html_e('Published links will appear here after they are curated in WordPress.', 'jot-library'); ?></p></div>
			<?php endif; ?>
		</section>
		<?php
		wp_reset_postdata();
		return (string) ob_get_clean();
	}

	/** @param array{action_url:string,search:string,topic:string} $context */
	private static function filter_url(array $context, string $topic): string {
		$args = array();
		if ('' !== $context['search']) {
			$args['jot_search'] = $context['search'];
		}
		if ('' !== $topic) {
			$args['jot_topic'] = $topic;
		}
		return add_query_arg($args, $context['action_url']);
	}

	/** @param array{action_url:string,search:string,topic:string} $context */
	private static function entry(int $post_id, array $context, int $position): string {
		$code = (string) get_post_meta($post_id, Entry_Service::META_CODE, true);
		$url = (string) get_post_meta($post_id, Entry_Service::META_URL, true);
		$source = (string) get_post_meta($post_id, Entry_Service::META_SOURCE, true);
		$description = trim(wp_strip_all_tags((string) get_the_excerpt($post_id)));
		$notes = trim(wp_strip_all_tags((string) get_post_field('post_content', $post_id)));
		if ($notes === $description) {
			$notes = '';
		}

		$meta = '<time class="jot-library__saved" datetime="' . esc_attr((string) get_the_date('c', $post_id)) . '">'
			. esc_html(sprintf(__('Saved %s', 'jot-library'), (string) get_the_date('j M Y', $post_id))) . '</time>';
		// Reading status is the curator's own bookkeeping, so only editors see it.
		if (current_user_can('edit_post', $post_id) && 'read' !== get_post_meta($post_id, Entry_Service::META_READING_STATUS, true)) {
			$meta .= '<span class="jot-library__unread">' . esc_html__('Unread', 'jot-library') . '</span>';
		}
		$terms = get_the_terms($post_id, Post_Type::TAXONOMY);
		if (is_array($terms)) {
			$meta .= '<ul class="jot-library__topics" aria-label="' . esc_attr__('Topics', 'jot-library') . '">';
			foreach ($terms as $term) {
				if ($term instanceof WP_Term) {
					$current = $context['topic'] === $term->slug ? ' aria-current="page"' : '';
					$meta .= '<li><a href="' . esc_url(self::filter_url($context, $term->slug)) . '"' . $current . '>' . esc_html($term->name) . '</a></li>';
				}
			}
			$meta .= '</ul>';
		}

		// Cards stay short: the curator's note wins, the publisher's summary fills in otherwise.
		if ('' !== $notes) {
			$body = '<p class="jot-library__note"><span class="screen-reader-text">' . esc_html__('Curator note:', 'jot-library') . ' </span>' . esc_html($notes) . '</p>';
		} elseif ('' !== $description) {
			$body = '<p class="jot-library__description">' . esc_html($description) . '</p>';
		} else {
			$body = '';
		}

		return '<li class="jot-library__entry" id="jot-library-item-' . $position . '">'
			. self::media($post_id, $code, $url)
			. '<div class="jot-library__header"><h3><a href="' . esc_url($url) . '" rel="noopener noreferrer">' . esc_html(get_the_title($post_id)) . '</a></h3>'
			. '<p class="jot-library__source">' . esc_html($source) . '</p></div>'
			. '<div class="jot-library__body">' . $body . '<div class="jot-library__meta">' . $meta . '</div></div>'
			. '</li>';
	}

	/**
	 * Featured image (copied from the page's og:image) framed like a print pinned into a
	 * notebook, with the code stamped on its corner as the copy control. Entries without
	 * an image get an index card with their glyph.
	 */
	private static function media(int $post_id, string $code, string $url): string {
		$print = '';
		$thumbnail_id = (int) get_post_thumbnail_id($post_id);
		if ($thumbnail_id > 0) {
			$image = wp_get_attachment_image(
				$thumbnail_id,
				'medium_large',
				false,
				array(
					'class' => 'jot-library__image',
					'alt' => '',
					'loading' => 'lazy',
					'decoding' => 'async',
					'sizes' => '(min-width: 52rem) 18rem, 40vw',
				)
			);
			if ('' !== $image) {
				// The title carries the accessible link; this duplicate stays out of the tab order.
				$print = '<a class="jot-library__print" href="' . esc_url($url) . '" rel="noopener noreferrer" tabindex="-1" aria-hidden="true">' . $image . '</a>';
			}
		}
		if ('' === $print) {
			$print = '<span class="jot-library__print jot-library__print--card" aria-hidden="true">' . Glyph::svg($code) . '</span>';
		}

		$status_id = wp_unique_id('jot-library-copy-status-');
		$stamp = '<span class="jot-library__copy">'
			. '<button class="jot-library__stamp" type="button" aria-describedby="' . esc_attr($status_id) . '" data-jot-copy-url="' . esc_url(home_url('/j/' . rawurlencode($code))) . '" data-jot-copy-success="' . esc_attr__('Short link copied', 'jot-library') . '" data-jot-copy-error="' . esc_attr__('Copy failed', 'jot-library') . '">'
			. '<span class="screen-reader-text">' . esc_html__('Copy short link', 'jot-library') . ' </span>'
			. '<span class="jot-library__code-value">' . esc_html($code) . '</span>'
			. '<svg class="jot-library__copy-icon" viewBox="0 0 16 16" aria-hidden="true" focusable="false"><rect x="5.5" y="5.5" width="8" height="8" rx="1.5" fill="none" stroke="currentColor" stroke-width="1.5"/><path d="M10.5 3.5v-.5a1.5 1.5 0 0 0-1.5-1.5H4A1.5 1.5 0 0 0 2.5 3v5A1.5 1.5 0 0 0 4 9.5h.5" fill="none" stroke="currentColor" stroke-width="1.5"/></svg>'
			. '</button><span class="jot-library__copy-status" id="' . esc_attr($status_id) . '" role="status" aria-live="polite" aria-atomic="true"></span></span>';

		return '<div class="jot-library__media" style="--jot-tilt:' . esc_attr(self::tilt($code)) . '">' . $print . $stamp . '</div>';
	}

	/** A small, stable rotation per code so the list looks hand-placed but never reshuffles. */
	private static function tilt(string $code): string {
		$angles = array('-3deg', '-2deg', '-1.25deg', '1.25deg', '2deg', '2.75deg');
		return $angles[crc32(Code::normalize($code)) % count($angles)];
	}

	public static function append_entry_details(string $content): string {
		if (! is_singular(Post_Type::TYPE) || ! in_the_loop() || ! is_main_query()) {
			return $content;
		}

		$post_id = get_the_ID();
		$code = (string) get_post_meta($post_id, Entry_Service::META_CODE, true);
		$url = (string) get_post_meta($post_id, Entry_Service::META_URL, true);
		$source = (string) get_post_meta($post_id, Entry_Service::META_SOURCE, true);
		$short = home_url('/j/' . rawurlencode($code));
		$identity = '<aside class="jot-library-entry" aria-label="' . esc_attr__('Jot reference', 'jot-library') . '">'
			. '<div class="jot-library-entry__identity">' . Glyph::svg($code) . '<div><p class="jot-library-entry__code">' . esc_html($code) . '</p>'
			. '<a class="jot-library-entry__short" href="' . esc_url($short) . '">' . esc_html($short) . '</a></div></div>'
			. '<p class="jot-library-entry__source">' . esc_html(sprintf(__('Source: %s', 'jot-library'), $source)) . '</p>'
			. '<p><a class="jot-library-entry__original" href="' . esc_url($url) . '" rel="noopener noreferrer">' . esc_html__('Visit original resource', 'jot-library') . '</a></p>'
			. '</aside>';

		return $identity . $content;
	}


	/** @param array{action_url:string,search:string,topic:string} $context */
	private static function load_more(WP_Query $query, array $context, int $page, int $page_size): string {
		$shown = count($query->posts);
		$total = (int) $query->found_posts;
		$progress = '<p class="jot-library__progress">' . esc_html(sprintf(__('Showing %1$s of %2$s', 'jot-library'), number_format_i18n($shown), number_format_i18n($total))) . '</p>';
		if ($shown >= $total || $page + 1 > max(1, intdiv(self::MAX_LOADED, $page_size))) {
			return $total > $page_size ? '<div class="jot-library__more">' . $progress . '</div>' : '';
		}

		$url = add_query_arg('jot_page', $page + 1, self::filter_url($context, $context['topic'])) . '#jot-library-item-' . ($shown + 1);
		return '<div class="jot-library__more">' . $progress
			. '<a class="jot-library__more-link" href="' . esc_url($url) . '" data-jot-load-more data-jot-loading="' . esc_attr__('Loading…', 'jot-library') . '" data-jot-loaded="' . esc_attr__('%s more entries loaded', 'jot-library') . '">' . esc_html__('Load more', 'jot-library') . '</a></div>';
	}
}
