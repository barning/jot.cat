<?php

declare(strict_types=1);

namespace JotLibrary;

use WP_Query;

final class Library_Block {
	public static function register(): void {
		register_block_type(JOT_LIBRARY_DIR . 'blocks/library');
	}

	/** @param array<string,mixed> $attributes */
	public static function render(array $attributes): string {
		$defaults = Settings::get();
		$page_size = min(48, max(1, absint($attributes['postsPerPage'] ?? $defaults['entries_per_page'])));
		$show_search = ! isset($attributes['showSearch']) || (bool) $attributes['showSearch'];
		$search = isset($_GET['jot_search']) ? sanitize_text_field(wp_unslash((string) $_GET['jot_search'])) : '';
		$topic = isset($_GET['jot_topic']) ? sanitize_title(wp_unslash((string) $_GET['jot_topic'])) : '';
		$page = isset($_GET['jot_page']) ? max(1, absint($_GET['jot_page'])) : 1;
		$args = array(
			'post_type' => Post_Type::TYPE,
			'post_status' => 'publish',
			'posts_per_page' => $page_size,
			'paged' => $page,
			's' => $search,
			'ignore_sticky_posts' => true,
		);
		if ('' !== $topic) {
			$args['tax_query'] = array(array('taxonomy' => Post_Type::TAXONOMY, 'field' => 'slug', 'terms' => $topic));
		}

		$query = new WP_Query($args);
		$wrapper = get_block_wrapper_attributes(array('class' => 'jot-library'));
		$action_url = get_permalink();
		if (! is_string($action_url) || '' === $action_url) {
			$action_url = home_url('/');
		}
		$search_id = wp_unique_id('jot-library-search-');
		$topic_id = wp_unique_id('jot-library-topic-');
		$topics = get_terms(array('taxonomy' => Post_Type::TAXONOMY, 'hide_empty' => true));
		if (is_wp_error($topics)) {
			$topics = array();
		}
		ob_start();
		?>
		<section <?php echo $wrapper; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by Core. ?>>
			<?php if ($show_search) : ?>
				<form class="jot-library__filters" method="get" action="<?php echo esc_url($action_url); ?>">
					<div class="jot-library__field jot-library__field--search">
						<label for="<?php echo esc_attr($search_id); ?>"><?php esc_html_e('Search bookmarks', 'jot-library'); ?></label>
						<input id="<?php echo esc_attr($search_id); ?>" name="jot_search" type="search" value="<?php echo esc_attr($search); ?>" placeholder="<?php echo esc_attr__('e.g. typography', 'jot-library'); ?>">
					</div>
					<div class="jot-library__field jot-library__field--topic">
						<label for="<?php echo esc_attr($topic_id); ?>"><?php esc_html_e('Topic', 'jot-library'); ?></label>
						<select id="<?php echo esc_attr($topic_id); ?>" name="jot_topic">
							<option value=""><?php esc_html_e('All topics', 'jot-library'); ?></option>
							<?php foreach ($topics as $term) : ?>
								<option value="<?php echo esc_attr($term->slug); ?>" <?php selected($topic, $term->slug); ?>><?php echo esc_html($term->name); ?></option>
							<?php endforeach; ?>
						</select>
					</div>
					<button type="submit"><?php esc_html_e('Filter bookmarks', 'jot-library'); ?></button>
					<?php if ('' !== $search || '' !== $topic) : ?>
						<a class="jot-library__clear" href="<?php echo esc_url($action_url); ?>"><?php esc_html_e('Clear filters', 'jot-library'); ?></a>
					<?php endif; ?>
				</form>
			<?php endif; ?>

			<p class="jot-library__count" role="status">
				<?php echo esc_html(sprintf(_n('%s published entry', '%s published entries', $query->found_posts, 'jot-library'), number_format_i18n($query->found_posts))); ?>
			</p>

			<?php if ($query->have_posts()) : ?>
				<ol class="jot-library__entries">
					<?php while ($query->have_posts()) : $query->the_post(); ?>
						<?php echo self::entry(get_the_ID()); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Method escapes dynamic values. ?>
					<?php endwhile; ?>
				</ol>
				<?php echo self::pagination($query, $search, $topic, $action_url); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Core-generated links are escaped. ?>
			<?php elseif ('' !== $search || '' !== $topic) : ?>
				<div class="jot-library__empty"><h3><?php esc_html_e('No matching entries', 'jot-library'); ?></h3><p><?php esc_html_e('Try another search or clear the filters.', 'jot-library'); ?></p><a href="<?php echo esc_url($action_url); ?>"><?php esc_html_e('Clear filters', 'jot-library'); ?></a></div>
			<?php else : ?>
				<div class="jot-library__empty"><h3><?php esc_html_e('The library is ready for its first entry', 'jot-library'); ?></h3><p><?php esc_html_e('Published links will appear here after they are curated in WordPress.', 'jot-library'); ?></p></div>
			<?php endif; ?>
		</section>
		<?php
		wp_reset_postdata();
		return (string) ob_get_clean();
	}

	public static function append_entry_details(string $content): string {
		if (! is_singular(Post_Type::TYPE) || ! in_the_loop() || ! is_main_query()) {
			return $content;
		}

		$post_id = get_the_ID();
		$code = (string) get_post_meta($post_id, Entry_Service::META_CODE, true);
		$url = (string) get_post_meta($post_id, Entry_Service::META_URL, true);
		$source = (string) get_post_meta($post_id, Entry_Service::META_SOURCE, true);
		$short = home_url('/j/' . rawurlencode($code));
		$identity = '<aside class="jot-library-entry" aria-label="' . esc_attr__('Jot reference', 'jot-library') . '">'
			. '<div class="jot-library-entry__identity">' . Glyph::svg($code) . '<div><p class="jot-library-entry__code">' . esc_html($code) . '</p>'
			. '<a class="jot-library-entry__short" href="' . esc_url($short) . '">' . esc_html($short) . '</a></div></div>'
			. '<p class="jot-library-entry__source">' . esc_html(sprintf(__('Source: %s', 'jot-library'), $source)) . '</p>'
			. '<p><a class="jot-library-entry__original" href="' . esc_url($url) . '" rel="noopener noreferrer">' . esc_html__('Visit original resource', 'jot-library') . '</a></p>'
			. '</aside>';

		return $identity . $content;
	}

	private static function entry(int $post_id): string {
		$code = (string) get_post_meta($post_id, Entry_Service::META_CODE, true);
		$url = (string) get_post_meta($post_id, Entry_Service::META_URL, true);
		$source = (string) get_post_meta($post_id, Entry_Service::META_SOURCE, true);
		$description = wp_strip_all_tags((string) get_the_excerpt($post_id));
		$notes = wp_strip_all_tags((string) get_post_field('post_content', $post_id));
		$terms = get_the_terms($post_id, Post_Type::TAXONOMY);
		$topics = '';
		if (is_array($terms)) {
			$topics = '<ul class="jot-library__topics">';
			foreach ($terms as $term) {
				$topics .= '<li>' . esc_html($term->name) . '</li>';
			}
			$topics .= '</ul>';
		}

		$content_text = '' !== $notes ? $notes : $description;
		$copy_status_id = wp_unique_id('jot-library-copy-status-');
		$short_url = home_url('/j/' . rawurlencode($code));

		return '<li class="jot-library__entry">'
			. '<div class="jot-library__content"><h3><a href="' . esc_url($url) . '" rel="noopener noreferrer">' . esc_html(get_the_title($post_id)) . '</a></h3>'
			. '<p class="jot-library__source">' . esc_html($source) . '</p>'
			. ('' !== $content_text ? '<p class="jot-library__description">' . esc_html($content_text) . '</p>' : '')
			. $topics
			. '<div class="jot-library__reference">'
			. '<span class="jot-library__copy"><button class="jot-library__code" type="button" aria-describedby="' . esc_attr($copy_status_id) . '" data-jot-copy-url="' . esc_url($short_url) . '" data-jot-copy-success="' . esc_attr__('Short link copied', 'jot-library') . '" data-jot-copy-error="' . esc_attr__('Copy failed', 'jot-library') . '">' . esc_html__('Copy short link', 'jot-library') . ' <span class="jot-library__code-value">' . esc_html($code) . '</span></button>'
			. '<span class="jot-library__copy-status" id="' . esc_attr($copy_status_id) . '" role="status" aria-live="polite" aria-atomic="true"></span></span></div>'
			. '</div></li>';
	}

	private static function pagination(WP_Query $query, string $search, string $topic, string $base_url): string {
		if ($query->max_num_pages < 2) {
			return '';
		}
		if ('' !== $search) {
			$base_url = add_query_arg('jot_search', $search, $base_url);
		}
		if ('' !== $topic) {
			$base_url = add_query_arg('jot_topic', $topic, $base_url);
		}
		$placeholder = 999999999;
		$base = str_replace((string) $placeholder, '%#%', add_query_arg('jot_page', $placeholder, $base_url));
		$links = paginate_links(array('base' => $base, 'format' => '', 'current' => max(1, absint($_GET['jot_page'] ?? 1)), 'total' => $query->max_num_pages, 'type' => 'list', 'prev_text' => __('Previous', 'jot-library'), 'next_text' => __('Next', 'jot-library')));
		return is_string($links) ? '<nav class="jot-library__pagination" aria-label="' . esc_attr__('Library pages', 'jot-library') . '">' . $links . '</nav>' : '';
	}
}
